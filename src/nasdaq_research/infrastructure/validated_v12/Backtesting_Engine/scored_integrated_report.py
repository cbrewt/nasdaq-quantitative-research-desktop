"""Append a Version 1.2 historical-score analysis to a *copy* of the discovery Word report.

The original screener report and JSON handoff remain unchanged. The report
clearly distinguishes current technical ranks from historical signal-date scores.
"""
from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt

from .integrated_report import REPORTS_DIR, _factor, _label_value, _pct, _table, _verify_screener_document


def generate_scored_integrated_report(result, screener_report: str | Path, *,
                                      output_dir: str | Path | None = None) -> Path:
    if result.backtest is None or not result.handoff.qualifying_tickers:
        raise ValueError("A nonempty completed Discovery Mode backtest is required.")
    if result.handoff.screener_settings.momentum_confirmation_required:
        raise ValueError("The scored integrated report requires a discovery-mode handoff.")
    source = Path(screener_report)
    if not source.is_file() or source.suffix.lower() != ".docx":
        raise FileNotFoundError(f"Screener Word report not found: {source}")
    doc = Document(source)
    h = result.handoff
    _verify_screener_document(doc, h)

    # Avoid silently pairing an old report with a newer same-date scan.
    summaries = [t for t in doc.tables if t.rows and t.rows[0].cells[0].text.strip() == "Symbol"]
    if not summaries:
        raise ValueError("Missing the stock summary table in the source Word document.")
    found = {r.cells[0].text.strip() for r in summaries[0].rows[1:]}
    if found != set(h.qualifying_tickers):
        raise ValueError("JSON tickers and the Word report's qualifying symbols differ. "
                         "Use the Word document generated by the same scan.")

    b = result.backtest
    sim = b.analysis.simulation
    doc.add_page_break()
    doc.add_heading("HISTORICAL SCORE-BASED BACKTESTING ANALYSIS", level=1)
    doc.add_paragraph(
        "Exploratory historical research for stocks selected by the current Discovery Mode scan. "
        "The scores below were calculated on each HISTORICAL signal date, not today's date."
    )
    _label_value(doc, "Scan ID", h.scan_id)
    _label_value(doc, "Scan date", h.scan_date)
    _label_value(doc, "Historical window", f"{result.start_date} through {result.end_date} (inclusive)")
    _label_value(doc, "Current discovery candidates", len(h.qualifying_tickers))
    _label_value(doc, "Tickers with usable historical data", len(b.analyzed_tickers))
    _label_value(doc, "Tickers excluded for historical-data reasons", len(b.excluded_tickers))
    _label_value(doc, "Reference trading sessions", len(result.trading_dates))
    _label_value(doc, "Generated (UTC)", datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"))

    s = h.screener_settings
    settings = h.backtest_settings
    doc.add_heading("Screening and Trade Simulation Settings", level=2)
    _table(doc, ("Parameter", "Value"), [
        ("Minimum 21-session gain", _pct(s.min_gain_pct)),
        ("Latest closing price range", f"${s.min_price:.2f}–${s.max_price:.2f}"),
        ("Momentum screening", "Discovery — price and gain only (scores classify signals)"),
        ("Technical score", "0–5; MACD > 0; histogram > 0; 3 rising histogram intervals; RSI 50–70; RVOL > 1"),
        ("Historical lookback", f"{settings.history_years} years"),
        ("Trade holding period", f"{settings.holding_sessions} trading sessions"),
        ("Estimated round-trip transaction costs", _pct(settings.round_trip_cost_pct)),
        ("Entry / exit", "Next session open / holding-period last-session close"),
    ])
    doc.add_heading("Historical Simulation Summary", level=2)
    _table(doc, ("Measurement", "Result"), [
        ("Historical price/gain-qualified signals", str(sim.total_signals)),
        ("Completed trades", str(len(sim.trades))),
        ("Overlapping signals skipped", str(sim.skipped_overlapping)),
        ("Incomplete trades skipped", str(sim.skipped_incomplete)),
        ("Tickers analyzed", ", ".join(b.analyzed_tickers)),
    ])

    # Keep this compact, decision-critical score table together at its start.
    doc.add_page_break()
    doc.add_heading("Historical Performance by Signal-Date Technical Score", level=2)
    doc.add_paragraph(
        "Each accepted simulated trade is assigned the score calculated on its own signal date. "
        "No completed trades in a score group is shown as N/A, not as a 0% win rate. "
        "A score is descriptive technical agreement, not an investment recommendation."
    )
    rows = []
    for group in b.score_groups:
        stats = group.statistics
        rows.append((
            "N/A" if group.score is None else f"{group.score}/5",
            str(group.signal_count), str(group.completed_trades),
            _pct(stats.win_rate_pct) if stats else "N/A",
            _pct(stats.expectancy_pct, signed=True, decimals=4) if stats else "N/A",
            _factor(stats.profit_factor) if stats else "N/A",
        ))
    _table(doc, ("Score", "Signals", "Completed trades", "Win rate", "Net expectancy", "Profit factor"), rows)

    if b.excluded_tickers:
        doc.add_heading("Historical Data Exclusions", level=2)
        _table(doc, ("Ticker", "Reason"), [(ticker, reason) for ticker, reason in b.excluded_tickers])
    else:
        doc.add_paragraph("All selected stocks had usable historical price data for the available reference sessions.")

    doc.add_heading("Completed Simulated Trades", level=2)
    if sim.trades:
        scores = {(item.signal.ticker, item.signal.signal_date): item.assessment.score
                  for item in b.scored_signals}
        trade_rows = []
        for trade in sim.trades:
            score = scores[(trade.ticker, trade.signal_date)]
            trade_rows.append((
                trade.ticker, str(trade.signal_date),
                "N/A" if score is None else f"{score}/5",
                str(trade.entry_date), str(trade.exit_date),
                _pct(trade.net_return_pct, signed=True),
            ))
        _table(doc, ("Ticker", "Signal date", "Historical score", "Entry date", "Exit date", "Net return"), trade_rows)
    else:
        doc.add_paragraph("No completed simulated trades in the selected window; performance metrics are unavailable.")

    limitations_heading = doc.add_heading("Limitations and Interpretation", level=2)
    limitations_heading.paragraph_format.page_break_before = True
    for note in (
        "Only stocks that qualify in the PRESENT scan are analyzed historically. "
        "This introduces selection/survivorship bias and does not establish a market-wide strategy edge.",
        "Historical membership of the Nasdaq and historical reverse-split eligibility are not reconstructed. "
        "The original current-day reverse-split exclusion is not a historical trade filter.",
        "Historical symbols with missing or discontinuous price bars are excluded and reported. "
        "Yahoo Finance price data, split adjustments, and corporate-action records may be incomplete or revised.",
        "A shared nonoverlapping-trade simulator prevents simultaneous positions in one stock; "
        "trading costs are estimated and realistic spreads, slippage, liquidity, and portfolio capital are not modeled.",
        "Small score groups can make win rates and expectancy highly unstable. "
        "This report is exploratory research and does not predict future returns or recommend trades.",
    ):
        doc.add_paragraph(note)
    footer = doc.add_paragraph("END OF SCORE-BASED RESEARCH REPORT")
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for run in footer.runs:
        run.bold = True
        run.font.size = Pt(8)

    destination = Path(output_dir) if output_dir is not None else REPORTS_DIR
    destination.mkdir(parents=True, exist_ok=True)
    base = f"Integrated_Scored_Nasdaq_Research_{h.scan_id}"
    path = destination / f"{base}.docx"
    counter = 2
    while path.exists():
        path = destination / f"{base}_{counter}.docx"
        counter += 1
        if counter > 9999:
            raise FileExistsError("Too many reports saved for this scan.")
    doc.save(path)
    if not path.is_file() or path.stat().st_size == 0:
        raise OSError(f"Integrated scored Word report not saved: {path}")
    return path
